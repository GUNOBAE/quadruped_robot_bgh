"""Build a fixed-base MuJoCo MJCF linkage preview from Fusion joint audit.

- Supports the compact reference generated by make_seed.py, or a user's full
  Fusion quadruped_joint_audit.json with the same assembly relationships.
- Preserves four legs and eight mechanical loops by 16 connect constraints.
- Illustrative primitive geometry, inertias, servo inputs, and foot endpoints.
- NOT gravity/contact simulation, standing, walking or reinforcement learning.
"""
from __future__ import annotations

import argparse
import json
import math
import re
import sys
from collections import deque
from pathlib import Path
from xml.etree import ElementTree as ET


def add(a, b):
    return [x + y for x, y in zip(a, b)]


def sub(a, b):
    return [x - y for x, y in zip(a, b)]


def scale(a, s):
    return [x * s for x in a]


def norm(a):
    return math.sqrt(sum(x * x for x in a))


def fmt(a):
    return " ".join(f"{v:.12g}" for v in a)


def build_graph(audit: dict) -> dict:
    occs = {o["path"]: o for o in audit["occurrences"]}
    parent = {p: p for p in occs}

    def find(p):
        while parent[p] != p:
            parent[p] = parent[parent[p]]
            p = parent[p]
        return p

    def union(a, b):
        parent[find(b)] = find(a)

    for group in audit.get("rigid_groups", []):
        names = group.get("occurrences", [])
        for name in names:
            if name not in occs:
                raise ValueError("Unknown rigid-group member: " + name)
        for name in names[1:]:
            union(names[0], name)

    candidates = [p for p in occs if p.rsplit("+", 1)[-1].startswith("base_link:")]
    if len(candidates) != 1:
        raise ValueError("Exactly one base_link occurrence is required")
    base = find(candidates[0])

    groups = {}
    for p in occs:
        groups.setdefault(find(p), []).append(p)
    rename = {g: ("BASE" if g == base else members[0]) for g, members in groups.items()}
    representative = {p: rename[find(p)] for p in occs}

    root = "BASE"
    nodes = list(rename.values())
    edges = []
    for j in audit.get("joints", []) + audit.get("as_built_joints", []):
        if j.get("is_suppressed"):
            continue
        if "RevoluteJointMotion" not in str(j.get("motion_type")):
            raise ValueError("Unsupported joint type: " + str(j.get("name")))
        a, b = representative[j["occurrence_1"]], representative[j["occurrence_2"]]
        if a == b:
            raise ValueError("Joint inside rigid group: " + j["name"])
        matrix = j.get("as_built_transform_cm")
        axis = j.get("rotation_axis_vector")
        if not matrix or len(matrix) != 16 or not axis or norm(axis) < 1e-9:
            raise ValueError("Missing frame/axis for " + j["name"])
        axis = [0.0 if abs(v) < 1e-8 else float(v) for v in axis]
        axis = scale(axis, 1 / norm(axis))
        edges.append(dict(
            name=j["name"], a=a, b=b,
            p=scale([matrix[3], matrix[7], matrix[11]], .01),
            axis=axis
        ))

    adj = {n: [] for n in nodes}
    for i, edge in enumerate(edges):
        adj[edge["a"]].append(i)
        adj[edge["b"]].append(i)

    def priority(name):
        for i, s in enumerate((
            "Servo_Mount", "femur", "servo_arm", "rodend_5mm", "tibia", "rodend_100mm"
        )):
            if name.startswith(s):
                return i
        return -1

    order, tree = [], []
    visited = {root}
    queue = deque([root])
    origins = {root: [0.0, 0.0, 0.0]}

    while queue:
        a = queue.popleft()
        order.append(a)
        neighbours = []
        for i in adj[a]:
            e = edges[i]
            b = e["b"] if e["a"] == a else e["a"]
            neighbours.append((priority(b), b, i))
        for _, b, i in sorted(neighbours):
            if b in visited:
                continue
            visited.add(b)
            queue.append(b)
            origins[b] = edges[i]["p"]
            tree.append(dict(edges[i], parent=a, child=b, edge_index=i))

    if len(visited) != len(nodes):
        raise ValueError("Disconnected assembly graph")

    selected = {t["edge_index"] for t in tree}
    loops = [e for i, e in enumerate(edges) if i not in selected]
    ids = {n: f"b{i:02d}" for i, n in enumerate(order)}
    drives = []
    for i, t in enumerate(tree):
        pair = t["parent"] + " " + t["child"]
        match = re.search(r"\b(FL|FR|BL|BR)_A", pair)
        if not match:
            continue
        role = None
        if t["parent"] == root:
            role = "coxa"
        elif t["child"].startswith("femur"):
            role = "femur_test"
        elif t["child"].startswith("Servo_Mount"):
            role = "mount_test"
        if role:
            drives.append(dict(tree_index=i, joint=t["name"], name=match[1] + "_" + role))

    feet = {}
    for n in nodes:
        if not n.startswith("tibia"):
            continue
        o = occs[n]
        if "preview_foot_proxy_cm" in o:
            feet[n] = scale(o["preview_foot_proxy_cm"], .01)
        elif o.get("bbox_min_cm") and o.get("center_of_mass_cm"):
            bbox = o["bbox_min_cm"]
            com = o["center_of_mass_cm"]
            feet[n] = scale([com[0], bbox[1] + .5, bbox[2] + .5], .01)

    segments = []
    for n in nodes:
        if n == root:
            continue
        for i in adj[n]:
            q = edges[i]["p"]
            if norm(sub(q, origins[n])) > 1e-7:
                segments.append(dict(body=n, a=origins[n], b=q))
        if n in feet:
            segments.append(dict(body=n, a=origins[n], b=feet[n]))

    if len(nodes) != 29 or len(tree) != 28 or len(loops) != 8 or len(drives) != 12:
        raise ValueError(
            f"Unexpected linkage layout: nodes={len(nodes)}, tree={len(tree)}, "
            f"loops={len(loops)}, test_inputs={len(drives)}. "
            "Verify the Fusion model before reusing this preview."
        )
    return dict(root=root, nodes=order, ids=ids, edges=edges, tree=tree,
                loops=loops, origins=origins, drives=drives,
                feet=feet, segments=segments,
                rigid_members={rename[g]: m for g, m in groups.items()})


def write_mjcf(g, destination):
    root = ET.Element("mujoco", model="BGH_linkage_preview_FIXED_BASE_NOT_RL")
    root.append(ET.Comment("Schematic shape, provisional inertias/inputs; not for hardware"))
    ET.SubElement(root, "compiler", angle="radian", autolimits="true",
                  inertiafromgeom="true")
    opt = ET.SubElement(root, "option", timestep=".001", gravity="0 0 0",
                        integrator="implicitfast", iterations="100")
    ET.SubElement(opt, "flag", contact="disable")
    visual = ET.SubElement(root, "visual")
    ET.SubElement(visual, "global", offwidth="1100", offheight="800")
    default = ET.SubElement(root, "default")
    ET.SubElement(default, "joint", type="hinge", limited="false",
                  damping=".01", armature=".0001")
    ET.SubElement(default, "geom", contype="0", conaffinity="0", density="1000")
    ET.SubElement(default, "site", size=".002", group="3")

    world = ET.SubElement(root, "worldbody")
    ET.SubElement(world, "light", pos="0 -.3 .7", dir="0 0 -1")
    ET.SubElement(world, "geom", name="visual_floor", type="plane",
                  size=".6 .6 .01", pos="0 0 -.14", rgba=".9 .9 .9 1")
    base = ET.SubElement(world, "body", name=g["ids"][g["root"]])
    ET.SubElement(base, "geom", name="SCHEMATIC_BODY_NOT_CAD",
                  type="box", pos=".0046 -.003 .015", size=".0525 .15 .025",
                  rgba=".35 .38 .42 1")

    bodies = {g["root"]: base}
    for t in g["tree"]:
        body = ET.SubElement(
            bodies[t["parent"]], "body",
            name=g["ids"][t["child"]],
            pos=fmt(sub(t["p"], g["origins"][t["parent"]]))
        )
        ET.SubElement(body, "joint", name=t["name"], axis=fmt(t["axis"]))
        ET.SubElement(body, "geom", type="sphere", size=".0035",
                      rgba=".25 .25 .28 1")
        bodies[t["child"]] = body

    for s in g["segments"]:
        pos = g["origins"][s["body"]]
        ET.SubElement(
            bodies[s["body"]], "geom", type="capsule", size=".0025",
            fromto=fmt(sub(s["a"], pos) + sub(s["b"], pos)),
            rgba=".55 .6 .65 1"
        )
    for name, foot in g["feet"].items():
        ET.SubElement(bodies[name], "geom", type="sphere", size=".005",
                      pos=fmt(sub(foot, g["origins"][name])),
                      rgba=".12 .12 .14 1")

    equality = ET.SubElement(root, "equality")
    for edge in g["loops"]:
        for k in (0, 1):
            q = add(edge["p"], scale(edge["axis"], .01 * k))
            sa = f"{edge['name']}_a{k}"
            sb = f"{edge['name']}_b{k}"
            ET.SubElement(bodies[edge["a"]], "site", name=sa,
                          pos=fmt(sub(q, g["origins"][edge["a"]])))
            ET.SubElement(bodies[edge["b"]], "site", name=sb,
                          pos=fmt(sub(q, g["origins"][edge["b"]])))
            ET.SubElement(
                equality, "connect", name=f"close_{edge['name']}_{k}",
                site1=sa, site2=sb,
                solref=".01 1", solimp=".95 .99 .001"
            )
    actuators = ET.SubElement(root, "actuator")
    for d in g["drives"]:
        ET.SubElement(actuators, "position", name=d["name"],
                      joint=d["joint"], kp="3", kv=".15",
                      ctrlrange="-.15 .15", forcerange="-.5 .5")
    ET.indent(root, space="  ")
    ET.ElementTree(root).write(destination, encoding="utf-8", xml_declaration=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("audit", type=Path)
    parser.add_argument("--out", type=Path,
                        default=Path(__file__).resolve().parent / "output")
    args = parser.parse_args()
    audit = json.loads(args.audit.read_text(encoding="utf-8-sig"))
    graph = build_graph(audit)
    args.out.mkdir(parents=True, exist_ok=True)
    write_mjcf(graph, args.out / "quadruped_preview.xml")
    manifest = {
        "source": str(args.audit),
        "source_provenance": audit.get("provenance", "user-provided full audit"),
        "limitations": [
            "No CAD geometry in baseline",
            "Fixed base; no gravity/contact",
            "Illustrative inertias and unverified servo mapping",
            "NOT a walking controller or RL environment",
        ],
        "bodies_including_fixed_base": len(graph["nodes"]),
        "tree_hinges": len(graph["tree"]),
        "cut_revolute_joints": len(graph["loops"]),
        "connect_constraints": len(graph["loops"]) * 2,
        "test_inputs": graph["drives"],
        "body_names": graph["ids"],
    }
    (args.out / "model_manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    print("Built:", args.out / "quadruped_preview.xml")
    print(f"Bodies={len(graph['nodes'])} tree={len(graph['tree'])} "
          f"closed_loops={len(graph['loops'])} test_inputs={len(graph['drives'])}")
    print("This is NOT a physical robot or walking simulation.")


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        print("BUILD FAILED:", exc, file=sys.stderr)
        raise
